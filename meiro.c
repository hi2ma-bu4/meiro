int px, py;
int stageNum = 0;	//ステージ数
int goal_count;		// 塗りつぶすべき床の数
int count;			// 塗りつぶした床の数
char chr[100000];	//次へ用

/* 最初の状態に戻る */
void play_start(void)
{
	int x, y;
	count = 0;
	px = 1;
	py = 1;
	for(y=0; y<GYO; y++)
		for(x=0; x<RETU; x++)
			if(meiro[stageNum][y][x] == 2) meiro[stageNum][y][x] = 0;
}

/* 塗りつぶすべき床の数をカウントする */ 
void goal_count_check(void)
{
	int x, y;
	goal_count = 0;
	for(y=0; y<GYO; y++)
		for(x=0; x<RETU; x++)
			if(meiro[stageNum][y][x] == 0) goal_count++;
}

/* 迷路を描く */
void draw_meiro(void)
{
	int x, y;
	for(y=0; y<GYO; y++){
		for(x=0; x<RETU; x++){
			if(x == px && y == py){
				meiro[stageNum][y][x] = 2;
				count ++;
				printf("\x1b[32m◎\x1b[39m");
			}
			else if(meiro[stageNum][y][x] == 0)
				printf("　"); // 全角スペース
			else if(meiro[stageNum][y][x] == 1)
				printf("■");
			else if(meiro[stageNum][y][x] == 2)
				printf("\x1b[36m×\x1b[39m");
		}
		printf("\n");
	}
	printf("move: ←↑→↓ restart: ESC\n");
}

/* キー入力判定 */
void key_input(void)
{
	int key;
	while (1) {
		if ( kbhit() ){
			key = getch();
			break;
		}
	}
	if((key == 119 || key == 72) && meiro[stageNum][py-1][px] == 0) // W, ↑キー
		py --;
	else if((key == 115 || key == 80) && meiro[stageNum][py+1][px] == 0) // S, ↓キー
		py ++;
	else if((key == 97 || key == 75) && meiro[stageNum][py][px-1] == 0) // A, ←キー
		px --;
	else if((key == 100 || key == 77) && meiro[stageNum][py][px+1] == 0) // D, →キー
		px ++;
	else if(key == 27) //ESCキー
		play_start();
	else if(key == 48) //0キー
	{
		stageNum++;
		goal_count_check();
		px = 1;
		py = 1;
		count = 0;
		play_start();
		system("cls");
		printf("ステージ %d\n", stageNum+1);
		draw_meiro();
		count = 0;
	}
	else
		key_input();
}

int main(void)
{
	px = 1;
	py = 1;
	count = 0;
	goal_count_check();

	while(1){
		system("cls");
		printf("ステージ %d\n", stageNum+1);
		draw_meiro();

		if(count == goal_count){
			stageNum++;
			if(stageNum >= DATANUM - 1){
				printf("クリア！\n");
				break;
			}
			goal_count_check();
			px = 1;
			py = 1;
			count = 0;
			play_start();
			printf("全て塗りました！\n\nEnter...");
			scanf("%c",&chr);
			system("cls");
			printf("ステージ %d\n", stageNum+1);
			draw_meiro();
		}
		key_input();
	}
	return 0;
}
